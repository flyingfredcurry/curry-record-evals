"""
agreement.py - how often the blind sitting agreed with the earlier call.

At the blind sitting (sheet dated 2026-10-19, sat 2026-10-21) Mike Curry ruled items whose
earlier call he could not see. For each such item the data files keep both: his ruling
is the label, the earlier call sits in `earlier` (faithful_claim) or `claude_call`
(same_person). This script counts, from the data files alone:

  blind vs Claude   items whose earlier call was Claude's read of the page
  blind vs July     items whose earlier call was Mike's own July 2026 sheet ruling,
                    held out of gold because the page text contradicted it on its face

Items with assurance blind-page were ruled again at the whole-page pass of 2026-10-21 (the
first sheet had shown a crop around the cited text); they count like blind: Claude's call
predates every pass. Two of them Claude had told Mike about before the first sheet (the
item's rationale says so); before pass 4 those two were reported apart as blind-told.

Agreement is an exact match. "No contradiction" also counts the cases where one side
abstained; a contradiction is SUPPORTED against UNSUPPORTED, or SAME against DIFFERENT.

  python tools/agreement.py > results/blind-sitting.md
"""
import json
import os
from collections import Counter

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ABSTAIN = {"faithful_claim": "CANNOT_BE_PROVEN", "same_person": "CANNOT_TELL"}


def load(name):
    with open(os.path.join(HERE, "data", name), encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def matrix(pairs, labels, abstain, title, row_name, col_name):
    """pairs: [(earlier, blind)]"""
    c = Counter(pairs)
    n = len(pairs)
    agree = sum(v for (e, b), v in c.items() if e == b)
    contra = sum(v for (e, b), v in c.items() if e != b and e != abstain and b != abstain)
    out = [f"### {title}", "",
           f"{n} items. Exact agreement {agree} ({agree / n:.0%}). Contradictions {contra} ({contra / n:.0%}). "
           f"The rest, {n - agree - contra}, are one side abstaining.", "",
           f"| {row_name} vs {col_name} | " + " | ".join(labels) + " |", "|---|" + "---|" * len(labels)]
    for e in labels:
        out.append(f"| {e} | " + " | ".join(str(c.get((e, b), 0)) for b in labels) + " |")
    return "\n".join(out) + "\n"


def main():
    fc = load("faithful_claim.jsonl")
    sp = load("same_person.jsonl")
    out = ["# The blind sitting: agreement with the earlier call (generated by tools/agreement.py)\n",
           "Mike Curry ruled every item below with the page in view and without the earlier call. "
           "His ruling is the label. The earlier call stays on the item. Counts come from the data files. "
           "Items with assurance blind-page were ruled again at the whole-page pass of 2026-10-21 (the first "
           "sheet had shown a crop around the cited text); the whole-page ruling is the one counted here.\n"]
    labs = ["SUPPORTED", "UNSUPPORTED", "CANNOT_BE_PROVEN"]
    ab = ABSTAIN["faithful_claim"]
    vs_claude = [(r["earlier"]["label"], r["label"]) for r in fc
                 if r.get("earlier") and r["assurance"] in ("blind", "blind-outside", "blind-page") and r["earlier"]["ruled_by"] == "claude"]
    vs_july = [(r["earlier"]["label"], r["label"]) for r in fc
               if r.get("earlier") and r["assurance"] in ("blind", "blind-outside", "blind-page") and r["earlier"]["ruled_by"] == "mike"]
    told = [(r["id"], r["earlier"]["label"], r["label"]) for r in fc if r["assurance"] == "blind-told"]
    out.append("## faithful_claim\n")
    if vs_claude:
        out.append(matrix(vs_claude, labs, ab, "Blind ruling against Claude's earlier read of the page", "Claude", "Mike, blind"))
    if vs_july:
        out.append(matrix(vs_july, labs, ab, "Blind ruling against Mike's own July 2026 sheet ruling (held items)", "July", "Mike, blind"))
    if told:
        out.append("Not counted above, assurance blind-told (Claude had told Mike what the page prints): "
                   + "; ".join(f"{i} July {e}, blind {b}" for i, e, b in told) + ".\n")
    labs2 = ["SAME", "DIFFERENT", "CANNOT_TELL"]
    ab2 = ABSTAIN["same_person"]
    sp_pairs = [(r["claude_call"], r["label"]) for r in sp
                if r["ruled_by"] == "mike" and r["assurance"] in ("blind", "blind-outside", "blind-page") and r.get("claude_call")]
    out.append("## same_person\n")
    if sp_pairs:
        out.append(matrix(sp_pairs, labs2, ab2, "Blind ruling against Claude's earlier call on the pair", "Claude", "Mike, blind"))
    outside = sum(1 for r in fc + sp if r["assurance"] == "blind-outside")
    out.append(f"Items ruled from knowledge outside the pages (assurance blind-outside): {outside}.\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
