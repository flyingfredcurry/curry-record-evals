"""card.py - write data/CARD.md: every count in it is computed from the data files."""
import json
import os
from collections import Counter

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(name):
    with open(os.path.join(HERE, "data", name), encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def table(rows, keys, title):
    c = Counter(tuple(r[k] for k in keys) for r in rows)
    out = [f"### {title}", "", "| " + " | ".join(keys) + " | items |", "|" + "---|" * (len(keys) + 1)]
    for k in sorted(c, key=lambda k: tuple(str(x) for x in k)):
        out.append("| " + " | ".join(str(x) for x in k) + f" | {c[k]} |")
    out.append(f"| total | " + " | " * (len(keys) - 1) + f"{len(rows)} |")
    return "\n".join(out) + "\n"


def main():
    fc, sp = load("faithful_claim.jsonl"), load("same_person.jsonl")
    pubs = Counter(r["source"]["publication"] for r in fc)
    years = Counter((r["source"]["date"] or "")[-4:] for r in fc)
    parts = ["# Data card (generated by tools/card.py; do not edit by hand)\n",
             table(fc, ["split", "assurance", "label"], "faithful_claim: items by split, assurance and label"),
             "Publications: " + ", ".join(f"{k} {v}" for k, v in pubs.most_common()) + ".\n",
             f"Distinct pages: {len({r['source']['source_page_id'] for r in fc})}. "
             f"Items whose cited text the page's OCR text does not contain: "
             f"{sum(not r['text_layer_has_mention'] for r in fc)}.\n",
             table(sp, ["split", "assurance", "label"], "same_person: items by split, assurance and label")]
    with open(os.path.join(HERE, "data", "CARD.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(parts))
    print("\n".join(parts))


if __name__ == "__main__":
    main()
